def load_docs(corpus_dir="sample-corpus"):
    """Паспорта документов корпуса: {doc_id: {поле: значение, 'raw': текст}}."""
    docs = {}
    for path in sorted(glob.glob(os.path.join(corpus_dir, "*.md"))):
        if path.endswith("INDEX.md"):
            continue
        with io.open(path, encoding="utf-8") as fh:
            text = fh.read()

        def field(name, _t=text):
            m = re.search(r"\|\s*" + re.escape(name) + r"\s*\|\s*([^|]+?)\s*\|", _t)
            return m.group(1) if m else ""

        doc_id = field("Идентификатор")
        if not doc_id:
            continue
        docs[doc_id] = dict(
            raw=text, vid=field("Вид"), podr=field("Подразделение"),
            otv=field("Ответственный"), kontur=field("Контур"),
            nom=field("Номенклатурная позиция"), ver=field("Версия"),
            vved=field("Дата введения"), hran=field("Срок хранения"),
            org=field("Организация"),
        )
    return docs


def verify(rows, docs, manifest_path="sample-corpus/manifest.json"):
    """Сверяет эталоны с корпусом и манифестом. Возвращает список ошибок."""
    errors = []
    base = {k: v for k, v in docs.items() if "редакция правила" not in v["vid"]}

    rules = {}
    if os.path.exists(manifest_path):
        with io.open(manifest_path, encoding="utf-8") as fh:
            manifest = json.load(fh)
        for rule in manifest.get("conflict_rules", []):
            rules[rule["key"]] = sorted(
                (r["effective"], r["doc_id"], r["value"]) for r in rule["revisions"]
            )

    for row in rows:
        q, kind, did, ans = row["question"], row["kind"], row["expected_doc_id"], row["expected_answer"]

        # каждый указанный doc_id существует в корпусе
        for one in (did or "").split(","):
            if one and one not in docs:
                errors.append(f"{q[:50]}: нет документа {one}")

        if kind == "fact":
            if ans not in docs[did]["raw"]:
                errors.append(f"{q[:50]}: значения «{ans}» нет в тексте {did}")

        elif kind == "calc":
            if "двух лет" in q:
                exp = [k for k, v in base.items() if v["hran"] == "не менее двух лет"]
                if ans != str(len(exp)) or (did and set(did.split(",")) != set(exp)):
                    errors.append(f"{q[:50]}: ожидалось {len(exp)} {sorted(exp)}, дано {ans}")
            elif "пяти лет" in q:
                exp = len([v for v in base.values() if v["hran"] == "не менее пяти лет"])
                if ans != str(exp):
                    errors.append(f"{q[:50]}: ожидалось {exp}, дано {ans}")
            elif "ПУ-45" in q:
                exp = [k for k, v in base.items() if v["nom"] == "подшипниковый узел ПУ-45"]
                if ans != str(len(exp)) or (did and set(did.split(",")) != set(exp)):
                    errors.append(f"{q[:50]}: ожидалось {len(exp)}")
            elif "версию 3.0" in q:
                exp = [k for k, v in base.items() if v["ver"] and float(v["ver"]) >= 3.0]
                if ans != str(len(exp)) or (did and set(did.split(",")) != set(exp)):
                    errors.append(f"{q[:50]}: ожидалось {len(exp)}")
            elif "раньше всех" in q:
                exp = min(base.items(), key=lambda kv: kv[1]["vved"])
                if did != exp[0] or ans != exp[1]["vved"]:
                    errors.append(f"{q[:50]}: ожидалось {exp[0]} {exp[1]['vved']}")
            elif "позже всех" in q:
                exp = max(base.items(), key=lambda kv: kv[1]["vved"])
                if did != exp[0] or ans != exp[1]["vved"]:
                    errors.append(f"{q[:50]}: ожидалось {exp[0]} {exp[1]['vved']}")
            elif "в 2026 году" in q:
                exp = [k for k, v in base.items() if v["vved"].startswith("2026")]
                if ans != str(len(exp)) or (did and set(did.split(",")) != set(exp)):
                    errors.append(f"{q[:50]}: ожидалось {len(exp)}")
            elif "Отдела качества" in q:
                exp = [k for k, v in base.items() if v["podr"] == "Отдел качества"]
                if ans != str(len(exp)) or (did and set(did.split(",")) != set(exp)):
                    errors.append(f"{q[:50]}: ожидалось {len(exp)}")
            elif "суммарная длительность" in q:
                exp = sum(STORAGE_YEARS.get(v["hran"], 0) for v in base.values())
                if ans != str(exp):
                    errors.append(f"{q[:50]}: ожидалось {exp}, дано {ans}")
            elif "Вектор-Пром" in q:
                exp = [k for k, v in base.items() if v["org"] == "АО «Вектор-Пром»"]
                if ans != str(len(exp)) or (did and set(did.split(",")) != set(exp)):
                    errors.append(f"{q[:50]}: ожидалось {len(exp)}")
            else:
                errors.append(f"{q[:50]}: нет правила проверки для расчётного вопроса")

        elif kind == "rule_asof":
            revs = rules.get(row["rule_key"])
            if not revs:
                errors.append(f"{q[:50]}: нет правила {row['rule_key']} в манифесте")
                continue
            as_of = row["as_of"]
            if as_of < revs[0][0]:
                errors.append(f"{q[:50]}: дата раньше первой редакции, должен быть отказ")
                continue
            act = [r for r in revs if r[0] <= as_of][-1]
            if (did, ans) != (act[1], act[2]):
                errors.append(f"{q[:50]}: ожидалось {act[1]} «{act[2]}», дано {did} «{ans}»")

        elif kind == "refuse":
            if not row["refusal_expected"]:
                errors.append(f"{q[:50]}: refuse без refusal_expected")
            if row["as_of"] and row["rule_key"] in rules:
                first = rules[row["rule_key"]][0][0]
                if row["as_of"] >= first:
                    errors.append(f"{q[:50]}: дата {row['as_of']} не раньше первой редакции {first}")

        elif kind == "journal":
            if did is not None:
                errors.append(f"{q[:50]}: journal-вопрос не должен указывать doc_id")

    return errors


def main(argv=None):
    ap = argparse.ArgumentParser(description="Генератор questions-prep50.jsonl")
    ap.add_argument("--verify", action="store_true",
                    help="только проверить эталоны против корпуса, файл не писать")
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args(argv)

    rows = _rows()
    docs = load_docs()
    errors = verify(rows, docs)

    counts = {}
    for r in rows:
        counts[r["kind"]] = counts.get(r["kind"], 0) + 1

    if errors:
        print(f"ОШИБКИ ЭТАЛОНОВ: {len(errors)}", file=sys.stderr)
        for e in errors:
            print("  " + e, file=sys.stderr)
        return 1

    if args.verify:
        print(f"проверено вопросов: {len(rows)}; ошибок нет")
        print("по классам:", json.dumps(counts, ensure_ascii=False, sort_keys=True))
        return 0

    with io.open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(f"записано: {len(rows)} -> {args.out}")
    print("по классам:", json.dumps(counts, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
